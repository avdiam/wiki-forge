#!/usr/bin/env python3
"""Regenerate wiki index files from page frontmatter.

Split index architecture: produces pages/indexes/index.md (table of contents)
plus per-type sub-indices (pages/indexes/index-sources.md, etc.).
Also writes .meta/index_stats.json for the conditional search threshold.

Deterministic output: pages are grouped by type, then by category, then
sorted alphabetically by slug within each group. Re-running on an unchanged
wiki produces byte-identical output (clean git diffs).

Usage:
    python update_index.py <wiki-root>

The wiki-root is the directory containing CLAUDE.md, pages/concepts/, pages/entities/, etc.
Only pure stdlib is used — no yaml library — so a minimal regex-based
frontmatter parser lives here.
"""

from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

from constants import PAGE_TYPES
from frontmatter import parse_frontmatter


TYPE_HEADINGS = {
    "sources": "Sources",
    "concepts": "Concepts",
    "entities": "Entities",
    "comparisons": "Comparisons",
    "syntheses": "Syntheses",
}


def collect_pages(wiki_root: Path) -> dict[str, list[dict]]:
    """Walk <type>/*.md and return parsed entries grouped by type.

    Pages live directly under wiki root: pages/concepts/, pages/entities/, etc.
    (no pages/ wrapper).
    """
    result: dict[str, list[dict]] = {t: [] for t in PAGE_TYPES}

    for page_type in PAGE_TYPES:
        type_dir = wiki_root / "pages" / page_type
        if not type_dir.is_dir():
            continue
        for md_file in sorted(type_dir.glob("*.md")):
            try:
                text = md_file.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            fm = parse_frontmatter(text)
            if not fm:
                continue
            entry = {
                "slug": md_file.stem,
                "title": fm.get("title") or md_file.stem,
                "summary": fm.get("summary") or "",
                "category": fm.get("category") or "uncategorized",
                "confidence": fm.get("confidence"),
                "sources": fm.get("sources") or [],
                "tags": fm.get("tags") or [],
                "aliases": fm.get("aliases") or [],
                "last_updated": fm.get("last_updated"),
                "stale": bool(fm.get("stale")),
            }
            result[page_type].append(entry)
    return result


def _format_entry_line(entry: dict) -> str:
    slug = entry["slug"]
    summary = entry.get("summary") or ""
    summary = re.sub(r"\s+", " ", summary).strip()

    # Build metadata suffix
    meta_parts = []
    conf = entry.get("confidence")
    if isinstance(conf, (int, float)):
        meta_parts.append(f"confidence: {conf}")
    sources = entry.get("sources") or []
    if isinstance(sources, list) and sources:
        meta_parts.append(f"sources: {len(sources)}")
    if entry.get("stale"):
        meta_parts.append("stale")

    meta = f" _({', '.join(meta_parts)})_" if meta_parts else ""

    # Build aliases/tags line — retrieval hints for LLM and BM25
    hints = []
    aliases = entry.get("aliases") or []
    if isinstance(aliases, list) and aliases:
        alias_strs = [str(a) for a in aliases if a]
        if alias_strs:
            hints.append(f"aka: {', '.join(alias_strs)}")
    tags = entry.get("tags") or []
    if isinstance(tags, list) and tags:
        tag_strs = [str(t) for t in tags if t]
        if tag_strs:
            hints.append(f"tags: {', '.join(tag_strs)}")

    hint_line = f" `[{' | '.join(hints)}]`" if hints else ""

    if summary:
        return f"- [[{slug}]] — {summary}{hint_line}{meta}"
    return f"- [[{slug}]]{hint_line}{meta}"


def write_indices(wiki_root: Path, pages_by_type: dict[str, list[dict]]) -> tuple[int, int]:
    """Write master index + per-type sub-indices into pages/indexes/. Returns (files_written, total_pages)."""
    total_pages = 0
    total_files = 0
    today = date.today().isoformat()

    indexes_dir = wiki_root / "pages" / "indexes"
    indexes_dir.mkdir(exist_ok=True)

    # Master index — table of contents pointing to sub-indices
    master_lines = [
        "# Wiki Master Index",
        "",
        f"_Auto-generated by `.scripts/update_index.py` on {today}. "
        "Do not hand-edit — changes will be overwritten on the next operation._",
        "",
    ]

    for page_type in PAGE_TYPES:
        entries = pages_by_type.get(page_type, [])
        type_total = len(entries)
        total_pages += type_total
        master_lines.append(
            f"- [[index-{page_type}]] — {TYPE_HEADINGS[page_type]} ({type_total} pages)"
        )

        # Write per-type sub-index
        lines: list[str] = [
            f"# {TYPE_HEADINGS[page_type]} Index",
            "",
            f"_Auto-generated on {today}._",
            f"**Total {page_type}:** {type_total}",
            "",
        ]

        if not entries:
            lines.append("_(empty)_")
            lines.append("")
        else:
            by_category: dict[str, list[dict]] = defaultdict(list)
            for e in entries:
                by_category[e["category"]].append(e)

            for category in sorted(by_category):
                lines.append(f"### {category}")
                lines.append("")
                for entry in sorted(by_category[category], key=lambda x: x["slug"]):
                    lines.append(_format_entry_line(entry))
                lines.append("")

        out_path = indexes_dir / f"index-{page_type}.md"
        out_path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
        total_files += 1

    master_lines.append("")
    master_lines.append(f"**Total pages:** {total_pages}")

    master_path = indexes_dir / "index.md"
    master_path.write_text("\n".join(master_lines).rstrip() + "\n", encoding="utf-8")
    total_files += 1

    return total_files, total_pages


def write_categories_index(wiki_root: Path, pages_by_type: dict[str, list[dict]]) -> None:
    """Write .meta/categories-index.json — the cached set of categories in use.

    Consumed by check_overview_triggers.py's new-category-trigger detection,
    which previously re-scanned every page frontmatter on every invocation.
    Cache is regenerated on every update_index.py run (i.e., every wiki
    operation), so consumers can read it without checking mtime.
    """
    meta_dir = wiki_root / ".meta"
    meta_dir.mkdir(exist_ok=True)
    cats: set[str] = set()
    total = 0
    for entries in pages_by_type.values():
        for e in entries:
            total += 1
            cat = e.get("category")
            if isinstance(cat, str) and cat.strip() and cat != "uncategorized":
                cats.add(cat.strip())
    payload = {
        "generated_at": date.today().isoformat(),
        "total_pages": total,
        "categories": sorted(cats),
    }
    out = meta_dir / "categories-index.json"
    out.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def write_stats(wiki_root: Path, total_pages: int) -> None:
    """Write .meta/index_stats.json for the conditional search threshold."""
    meta_dir = wiki_root / ".meta"
    meta_dir.mkdir(exist_ok=True)
    
    # Compute inbound links for hub dampening
    inbound_counts = {}
    try:
        import sys
        scripts_dir = str(wiki_root / ".scripts")
        if scripts_dir not in sys.path:
            sys.path.insert(0, scripts_dir)
        from graph_analyzer import build_graph
        _, _, inbound = build_graph(wiki_root)
        inbound_counts = {slug: len(sources) for slug, sources in inbound.items()}
    except Exception as e:
        print(f"warning: failed to compute graph stats for index_stats.json: {e}", file=sys.stderr)

    # Estimate tokens across all index files in pages/indexes/
    indexes_dir = wiki_root / "pages" / "indexes"
    total_words = 0
    if indexes_dir.is_dir():
        for idx_file in indexes_dir.glob("index*.md"):
            try:
                text = idx_file.read_text(encoding="utf-8")
                total_words += len(text.split())
            except OSError:
                continue

    estimated_tokens = int(total_words * 1.3)

    stats = {
        "total_pages": total_pages,
        "estimated_tokens": estimated_tokens,
        "generated_at": date.today().isoformat(),
        "inbound_links": inbound_counts,
    }
    stats_path = meta_dir / "index_stats.json"
    stats_path.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print("usage: update_index.py <wiki-root>", file=sys.stderr)
        return 2
    wiki_root = Path(argv[1]).resolve()
    if not (wiki_root / "CLAUDE.md").is_file():
        print(f"error: {wiki_root} does not look like a wiki root (no CLAUDE.md)", file=sys.stderr)
        return 2

    pages = collect_pages(wiki_root)
    files_written, total_pages = write_indices(wiki_root, pages)
    write_categories_index(wiki_root, pages)
    write_stats(wiki_root, total_pages)
    print(f"wrote {files_written} index files ({total_pages} pages total)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
